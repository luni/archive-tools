#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]:-$0}")" && pwd)"
# shellcheck source=common.sh
source "${SCRIPT_DIR}/common.sh"

usage() {
  cat <<'EOF'
Usage:
  find-duplicate-sha256.sh [OPTIONS] [DIRECTORY...]

Description:
  Recursively scans the provided directories (defaults to ".") for files
  generated by analyze-archive.sh (suffix ".sha256") and reports any SHA-256
  digests that appear more than once. Each duplicate lists the manifest file
  and the archived path associated with that digest so you can spot redundant
  content across archives quickly.

Options:
  -A, --identical-archives   Only report archives whose manifests are identical
                             (same set of files + hashes). Requires sha256sum.
  -D, --delete-identical     Delete redundant archives/manifests when using
                             --identical-archives. Keeps the first archive in
                             each identical group and removes the rest.
  -S, --skip-intra-manifest  Ignore hashes that appear more than once inside the
                             same manifest (only care about cross-archive dupes).
  -y, --yes                  Automatically answer "yes" to deletion prompts.
  -h, --help                 Show this help message.
EOF
}

require_tool() {
  command -v "$1" >/dev/null 2>&1 || die "Required tool '$1' is not on PATH."
}

SEP=$'\x1F'
GROUP_SEP=$'\x1E'
IDENTICAL_ONLY=0
SKIP_INTRA_MANIFEST=0
DELETE_IDENTICAL=0
AUTO_CONFIRM=0

declare -A SIGNATURE_MANIFESTS=()
declare -A MANIFEST_ENTRY_COUNTS=()

RECORDS_FILE="$(mktemp)"
trap 'rm -f "$RECORDS_FILE"' EXIT

# Escape glob metacharacters so a filename can be embedded in a glob pattern
# and still match only itself.
glob_escape() {
  local s="$1" out="" i c
  for ((i = 0; i < ${#s}; i++)); do
    c="${s:i:1}"
    case "$c" in
    \* | \? | \[ | \] | \\) out+="\\$c" ;;
    *) out+="$c" ;;
    esac
  done
  printf '%s' "$out"
}

collect_related_basename_files() {
  local manifest="$1" archive="$2" out_var="$3"
  local -n __out_ref="$out_var"
  __out_ref=()

  local base_no_sha="${manifest%.sha256}" dir stem
  dir="$(dirname -- "$manifest")"
  stem="$(basename -- "$base_no_sha")"

  # Narrow allowlist: only archive payloads, split chunks, and
  # manifest-adjacent sidecars belong to an archive's file group. A free
  # 'stem.*' glob would also sweep up unrelated documents (notes, logs,
  # other data files) sharing the prefix.
  local -a file_exts=(
    tar tar.gz tgz tar.xz txz tlz tar.lzma tar.bz2 tbz tbz2 tar.zst tzst tar.Z taz
    7z zip rar
    sha1 md5 sfv sig meta torrent nfo info
  )
  # Split-chunk suffix patterns (the [0-9] classes stay active below; only
  # the stem is glob-escaped).
  local -a split_globs=(
    "7z.[0-9][0-9][0-9]" "zip.[0-9][0-9][0-9]" "rar.[0-9][0-9][0-9]"
    "z[0-9][0-9]" "r[0-9][0-9]" "part[0-9]*.rar"
  )

  declare -A seen=()
  local candidate ext g esc_dir esc_stem
  esc_dir="$(glob_escape "$dir")"
  esc_stem="$(glob_escape "$stem")"

  for ext in "${file_exts[@]}"; do
    candidate="$dir/$stem.$ext"
    [[ -f "$candidate" ]] || continue
    if [[ "$candidate" == "$manifest" || (-n "${archive:-}" && "$candidate" == "$archive") ]]; then
      continue
    fi
    seen["$candidate"]=1
  done

  for g in "${split_globs[@]}"; do
    while IFS= read -r candidate; do
      [[ -f "$candidate" ]] || continue
      if [[ "$candidate" == "$manifest" || (-n "${archive:-}" && "$candidate" == "$archive") ]]; then
        continue
      fi
      seen["$candidate"]=1
    done < <(compgen -G "$esc_dir/$esc_stem.$g")
  done

  for candidate in "${!seen[@]}"; do
    __out_ref+=("$candidate")
  done
}

gather_delete_targets() {
  local manifest="$1" out_var="$2"
  local -n __out_ref="$out_var"
  __out_ref=()

  local archive=""
  if [[ -e "$manifest" ]]; then
    __out_ref+=("$manifest")
  fi

  # The archive is the manifest path minus the .sha256 suffix — under the
  # current naming convention that is the exact archive filename, e.g.
  # "a.tar.sha256" describes "a.tar". -f (not -e) so a directory or fifo
  # that happens to share the name is never queued for rm -f.
  if [[ "$manifest" == *.sha256 ]]; then
    archive="${manifest%.sha256}"
    if [[ -f "$archive" ]]; then
      __out_ref+=("$archive")
    fi
  fi

  local -a related_files=()
  collect_related_basename_files "$manifest" "${archive:-}" related_files
  if ((${#related_files[@]} > 0)); then
    __out_ref+=("${related_files[@]}")
  fi
}

format_manifest_choice_label() {
  local manifest="$1"
  local -a targets=()
  gather_delete_targets "$manifest" targets

  local label="$manifest"
  if ((${#targets[@]} > 1)); then
    local -a extras=("${targets[@]:1}")
    label+=" (also removes: "
    label+="$(printf '%s, ' "${extras[@]}")"
    label="${label%, }"
    label+=")"
  fi
  printf '%s\n' "$label"
}

interactive_select_items() {
  local result_var="$1"
  local prompt="$2"
  shift 2
  local -n __result_ref="$result_var"
  local -a options=("$@")
  __result_ref=()

  if ((${#options[@]} == 0)); then
    return 1
  fi

  if command -v fzf >/dev/null 2>&1; then
    local selection
    if ! selection="$(
      printf '%s\n' "${options[@]}" |
        fzf --multi --prompt "$prompt" \
          --header=$'TAB to toggle selections, ENTER to confirm, ESC to cancel'
    )"; then
      return 1
    fi
    if [[ -z "$selection" ]]; then
      return 1
    fi
    mapfile -t __result_ref <<<"$selection"
    return 0
  fi

  while true; do
    printf '%s\n' "$prompt"
    for idx in "${!options[@]}"; do
      printf '  [%d] %s\n' "$((idx + 1))" "${options[idx]}"
    done
    printf 'Enter comma-separated numbers to delete (blank to cancel): '
    local input
    if ! IFS= read -r input; then
      return 1
    fi
    input="${input//[[:space:]]/}"
    if [[ -z "$input" ]]; then
      return 1
    fi
    IFS=',' read -r -a selected_indices <<<"$input"
    declare -a selected_unique=()
    declare -A seen_index=()
    local invalid=0
    for raw in "${selected_indices[@]}"; do
      if [[ ! "$raw" =~ ^[0-9]+$ ]]; then
        invalid=1
        break
      fi
      local idx=$((raw - 1))
      if ((idx < 0 || idx >= ${#options[@]})); then
        invalid=1
        break
      fi
      if [[ -z "${seen_index[$idx]:-}" ]]; then
        selected_unique+=("${options[idx]}")
        seen_index[$idx]=1
      fi
    done
    if ((invalid || ${#selected_unique[@]} == 0)); then
      printf 'Invalid selection. Please try again.\n'
      continue
    fi
    __result_ref=("${selected_unique[@]}")
    return 0
  done
}

delete_redundant_manifest() {
  local manifest="$1"
  local -a targets=()
  gather_delete_targets "$manifest" targets

  if [[ "${#targets[@]}" -eq 0 ]]; then
    printf 'warning: nothing to delete for %s (files missing)\n' "$manifest" >&2
    return
  fi

  if confirm_action "The following ${#targets[@]} item(s) will be removed:" "$AUTO_CONFIRM" "${targets[@]}"; then
    for path in "${targets[@]}"; do
      if rm -f -- "$path"; then
        printf 'Deleted %s\n' "$path"
      else
        printf 'Failed to delete %s\n' "$path" >&2
      fi
    done
  fi
}

entries_recorded=0
lines_skipped=0

# Parse one manifest with awk: appends "hash SEP manifest SEP entry" records to
# RECORDS_FILE and (in --identical-archives mode) "hash SEP entry" pairs to a
# per-manifest file used for the content signature. Accepts the sha256sum-style
# "hash  path  size" layout as well as looser "hash path" variants.
process_manifest() {
  local manifest="$1"
  local pairs_file=""
  ((IDENTICAL_ONLY)) && pairs_file="$(mktemp)"

  local stats
  if ! stats="$(awk -v manifest="$manifest" -v sep="$SEP" \
      -v records="$RECORDS_FILE" -v pairs="$pairs_file" '
    {
      line = $0
      sub(/\r$/, "", line)
      lineno++
      if (line == "" || line ~ /^[[:space:]]*#/ || line ~ /^%%/) next
      if (match(line, /^[[:xdigit:]]{64}[ \t]+/)) {
        hash = substr(line, 1, 64)
        rest = substr(line, RLENGTH + 1)
        entry = rest
        if (match(rest, /[ \t][ \t]+[0-9]+$/)) entry = substr(rest, 1, RSTART - 1)
        print hash sep manifest sep entry >> records
        if (pairs != "") print hash sep entry >> pairs
        ok++
      } else {
        skipped++
        printf "warning: %s:%d not recognized, skipping\n", manifest, lineno > "/dev/stderr"
      }
    }
    END { printf "%d %d", ok + 0, skipped + 0 }
  ' "$manifest")"; then
    [[ -n "$pairs_file" ]] && rm -f "$pairs_file"
    die "Failed to parse manifest: $manifest"
  fi

  local manifest_entries manifest_skipped
  read -r manifest_entries manifest_skipped <<<"$stats"
  entries_recorded=$((entries_recorded + manifest_entries))
  lines_skipped=$((lines_skipped + manifest_skipped))
  MANIFEST_ENTRY_COUNTS["$manifest"]=$manifest_entries

  if [[ "$manifest_entries" -eq 0 ]]; then
    printf 'note: %s contained no recognizable entries\n' "$manifest" >&2
  fi

  if ((IDENTICAL_ONLY)); then
    local signature
    signature="$(LC_ALL=C sort "$pairs_file" | sha256sum | awk '{print $1}')"
    rm -f "$pairs_file"
    if [[ -v SIGNATURE_MANIFESTS["$signature"] ]]; then
      SIGNATURE_MANIFESTS["$signature"]+="$GROUP_SEP$manifest"
    else
      SIGNATURE_MANIFESTS["$signature"]="$manifest"
    fi
  fi
}

dirs=()
while [[ $# -gt 0 ]]; do
  case "$1" in
  -A | --identical-archives)
    IDENTICAL_ONLY=1
    shift
    ;;
  -D | --delete-identical)
    DELETE_IDENTICAL=1
    shift
    ;;
  -S | --skip-intra-manifest)
    SKIP_INTRA_MANIFEST=1
    shift
    ;;
  -y | --yes)
    AUTO_CONFIRM=1
    shift
    ;;
  -h | --help)
    usage
    exit 0
    ;;
  --)
    shift
    break
    ;;
  -*)
    die "Unknown option: $1"
    ;;
  *)
    dirs+=("$1")
    shift
    ;;
  esac
done

if [[ $# -gt 0 ]]; then
  dirs+=("$@")
fi

if [[ "${#dirs[@]}" -eq 0 ]]; then
  dirs=(".")
fi

if ((DELETE_IDENTICAL && !IDENTICAL_ONLY)); then
  die "--delete-identical requires --identical-archives"
fi

for dir in "${dirs[@]}"; do
  [[ -d "$dir" ]] || die "Directory not found: $dir"
done

if ((IDENTICAL_ONLY)); then
  require_tool sha256sum
fi

manifests_scanned=0
while IFS= read -r -d '' manifest; do
  manifests_scanned=$((manifests_scanned + 1))
  process_manifest "$manifest"
done < <(find "${dirs[@]}" -type f -name '*.sha256' -print0)

if [[ "$manifests_scanned" -eq 0 ]]; then
  die "No .sha256 manifests found under the provided directory set."
fi

unique_hashes="$(awk -v sep="$SEP" 'BEGIN { FS = sep } { print $1 }' "$RECORDS_FILE" | LC_ALL=C sort -u | wc -l)"

printf 'Scanned %d manifest(s); %d total entries (%d unique hashes). Skipped %d line(s).\n' \
  "$manifests_scanned" "$entries_recorded" "$unique_hashes" "$lines_skipped"

if ((IDENTICAL_ONLY)); then
  identical_groups_found=0
  for signature in "${!SIGNATURE_MANIFESTS[@]}"; do
    IFS=$GROUP_SEP read -r -a manifests_in_group <<<"${SIGNATURE_MANIFESTS["$signature"]}"
    if ((${#manifests_in_group[@]} > 1)); then
      identical_groups_found=1
      mapfile -t manifests_in_group < <(printf '%s\n' "${manifests_in_group[@]}" | LC_ALL=C sort)
      entries="${MANIFEST_ENTRY_COUNTS["${manifests_in_group[0]}"]:-0}"
      printf '\nArchives with identical contents (%d entries):\n' "$entries"
      for manifest in "${manifests_in_group[@]}"; do
        printf '  - %s\n' "$manifest"
      done
      if ((DELETE_IDENTICAL)); then
        declare -a manifests_to_delete=()
        if ((AUTO_CONFIRM)); then
          manifests_to_delete=("${manifests_in_group[@]:1}")
          printf 'Auto mode: keeping %s and deleting %d additional archive(s).\n' \
            "${manifests_in_group[0]}" "${#manifests_to_delete[@]}"
        else
          declare -a choice_labels=()
          declare -A label_to_manifest=()
          for manifest in "${manifests_in_group[@]}"; do
            label="$(format_manifest_choice_label "$manifest")"
            choice_labels+=("$label")
            label_to_manifest["$label"]="$manifest"
          done
          printf $'Select redundant archives to delete. Leave at least one archive unchecked.\n'
          declare -a selected_labels=()
          if ! interactive_select_items selected_labels "delete> " "${choice_labels[@]}"; then
            printf 'No archives were selected for deletion; skipping this group.\n'
            continue
          fi
          for label in "${selected_labels[@]}"; do
            manifest="${label_to_manifest["$label"]-}"
            if [[ -z "$manifest" ]]; then
              printf 'warning: selection "%s" did not map to a manifest, skipping\n' "$label" >&2
              continue
            fi
            manifests_to_delete+=("$manifest")
          done
          if ((${#manifests_to_delete[@]} >= ${#manifests_in_group[@]})); then
            printf 'Cannot delete every archive in a group; skipping this group.\n'
            continue
          fi
        fi
        for manifest in "${manifests_to_delete[@]}"; do
          delete_redundant_manifest "$manifest"
        done
      fi
    fi
  done

  if ((identical_groups_found == 0)); then
    printf 'No archives with identical contents were found.\n'
  elif ((DELETE_IDENTICAL)); then
    printf '\nDeletion pass complete.\n'
  fi
  exit 0
fi

# Aggregate records grouped by hash (sorted stream): counts occurrences and
# unique manifests per hash, then prints the duplicate report on the fly.
duplicate_report="$(
  LC_ALL=C sort -t "$SEP" -k1,1 -- "$RECORDS_FILE" | awk -v sep="$SEP" -v skip="$SKIP_INTRA_MANIFEST" '
    BEGIN { prev = ""; cnt = 0; ucnt = 0; n = 0 }
    function flush(   qualified, shown, i) {
      if (prev == "") return
      qualified = skip ? (ucnt > 1) : (cnt > 1)
      if (!qualified) return
      printf "\nSHA256 %s (%d occurrences):\n", prev, (skip ? ucnt : cnt)
      for (i = 1; i <= n; i++) {
        if (skip) {
          if (man[i] in shown) continue
          shown[man[i]] = 1
        }
        printf "  - %s :: %s\n", man[i], ent[i]
      }
    }
    {
      p1 = index($0, sep)
      rest = substr($0, p1 + 1)
      p2 = index(rest, sep)
      h = substr($0, 1, p1 - 1)
      m = substr(rest, 1, p2 - 1)
      e = substr(rest, p2 + 1)
      if (h != prev) {
        flush()
        prev = h; cnt = 0; ucnt = 0; n = 0
        delete seenm; delete man; delete ent
      }
      cnt++
      if (!(m in seenm)) { seenm[m] = 1; ucnt++ }
      n++; man[n] = m; ent[n] = e
    }
    END { flush() }
  '
)"

if [[ -z "$duplicate_report" ]]; then
  printf 'No duplicate SHA-256 entries found.\n'
  exit 0
fi

printf '\nDuplicate SHA-256 digests:%s\n' "$duplicate_report"
